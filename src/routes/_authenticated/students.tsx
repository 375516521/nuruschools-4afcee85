import { createFileRoute } from "@tanstack/react-router";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";
import { Plus, Loader2, Search } from "lucide-react";
import { toast } from "sonner";
import { z } from "zod";

import { supabase } from "@/integrations/supabase/client";
import { AppShell, useSession } from "@/components/AppShell";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Badge } from "@/components/ui/badge";
import {
  Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle, DialogTrigger,
} from "@/components/ui/dialog";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";

export const Route = createFileRoute("/_authenticated/students")({
  component: StudentsPage,
});

const STATUSES = ["all", "active", "deactivated", "graduated", "archived", "transferred_out"] as const;

const learnerSchema = z.object({
  first_name: z.string().trim().min(1, "First name is required").max(60),
  last_name: z.string().trim().min(1, "Last name is required").max(60),
  gender: z.string().nullable(),
  grade_id: z.string().uuid("Select a grade"),
  stream_id: z.string().uuid().nullable(),
  guardian_name: z.string().trim().max(80).nullable(),
  guardian_phone: z.string().trim().max(20).nullable(),
});

function StudentsPage() {
  const { data: session } = useSession();
  const schoolId = (session?.profile as { school_id?: string } | null)?.school_id ?? null;
  const qc = useQueryClient();
  const [status, setStatus] = useState<string>("active");
  const [q, setQ] = useState("");
  const [open, setOpen] = useState(false);
  const [gradeId, setGradeId] = useState<string>("");
  const [streamId, setStreamId] = useState<string>("");

  const { data: grades } = useQuery({
    queryKey: ["grades", schoolId],
    enabled: !!schoolId,
    queryFn: async () => (await supabase.from("grades").select("*").eq("school_id", schoolId!).order("level_order")).data ?? [],
  });

  const { data: streams } = useQuery({
    queryKey: ["streams", gradeId],
    enabled: !!gradeId,
    queryFn: async () => (await supabase.from("streams").select("*").eq("grade_id", gradeId).order("name")).data ?? [],
  });

  const { data: students, isLoading } = useQuery({
    queryKey: ["students", schoolId, status],
    enabled: !!schoolId,
    queryFn: async () => {
      let query = supabase
        .from("students")
        .select("*, grades(name), streams(name)")
        .eq("school_id", schoolId!)
        .order("adm_no");
      if (status !== "all") query = query.eq("status", status as "active");
      return (await query).data ?? [];
    },
  });

  const create = useMutation({
    mutationFn: async (form: FormData) => {
      const parsed = learnerSchema.safeParse({
        first_name: form.get("first_name"),
        last_name: form.get("last_name"),
        gender: form.get("gender") || undefined,
        grade_id: gradeId,
        stream_id: streamId || null,
        guardian_name: form.get("guardian_name") || undefined,
        guardian_phone: form.get("guardian_phone") || undefined,
      });
      if (!parsed.success) throw new Error(parsed.error.issues[0]!.message);
      // adm_no and student_id are generated by the database trigger when left empty.
      const { error } = await supabase.from("students").insert({ ...parsed.data, adm_no: "", school_id: schoolId! });
      if (error) throw error;
    },
    onSuccess: () => {
      toast.success("Learner admitted — admission number and student ID generated.");
      setOpen(false); setGradeId(""); setStreamId("");
      void qc.invalidateQueries({ queryKey: ["students"] });
    },
    onError: (e: Error) => toast.error(e.message),
  });

  const filtered = (students ?? []).filter((s) => {
    const t = q.trim().toLowerCase();
    if (!t) return true;
    return `${s.first_name} ${s.last_name} ${s.adm_no} ${s.student_id ?? ""}`.toLowerCase().includes(t);
  });

  return (
    <AppShell
      title="Learners"
      subtitle={`${filtered.length} shown`}
      actions={
        <Dialog open={open} onOpenChange={setOpen}>
          <DialogTrigger asChild><Button size="sm"><Plus className="size-4" /> Admit learner</Button></DialogTrigger>
          <DialogContent>
            <DialogHeader>
              <DialogTitle>Admit a new learner</DialogTitle>
              <DialogDescription>The admission number and student ID are generated automatically and cannot be edited.</DialogDescription>
            </DialogHeader>
            <form
              onSubmit={(e) => { e.preventDefault(); create.mutate(new FormData(e.currentTarget)); }}
              className="space-y-3"
            >
              <div className="grid gap-3 sm:grid-cols-2">
                <div className="space-y-1.5"><Label htmlFor="fn">First name</Label><Input id="fn" name="first_name" required /></div>
                <div className="space-y-1.5"><Label htmlFor="ln">Last name</Label><Input id="ln" name="last_name" required /></div>
              </div>
              <div className="grid gap-3 sm:grid-cols-2">
                <div className="space-y-1.5">
                  <Label>Grade</Label>
                  <Select value={gradeId} onValueChange={(v) => { setGradeId(v); setStreamId(""); }}>
                    <SelectTrigger><SelectValue placeholder="Select grade" /></SelectTrigger>
                    <SelectContent>
                      {(grades ?? []).map((g) => <SelectItem key={g.id} value={g.id}>{g.name}</SelectItem>)}
                    </SelectContent>
                  </Select>
                </div>
                <div className="space-y-1.5">
                  <Label>Stream</Label>
                  <Select value={streamId} onValueChange={setStreamId} disabled={!gradeId}>
                    <SelectTrigger><SelectValue placeholder="Select stream" /></SelectTrigger>
                    <SelectContent>
                      {(streams ?? []).map((s) => <SelectItem key={s.id} value={s.id}>{s.name}</SelectItem>)}
                    </SelectContent>
                  </Select>
                </div>
              </div>
              <div className="grid gap-3 sm:grid-cols-2">
                <div className="space-y-1.5"><Label htmlFor="gn">Guardian name</Label><Input id="gn" name="guardian_name" /></div>
                <div className="space-y-1.5"><Label htmlFor="gp">Guardian phone</Label><Input id="gp" name="guardian_phone" placeholder="0722000111" /></div>
              </div>
              <DialogFooter>
                <Button type="submit" disabled={create.isPending}>
                  {create.isPending ? <Loader2 className="size-4 animate-spin" /> : null} Admit learner
                </Button>
              </DialogFooter>
            </form>
          </DialogContent>
        </Dialog>
      }
    >
      <div className="mb-4 flex flex-wrap gap-3">
        <div className="relative min-w-52 flex-1">
          <Search className="absolute top-1/2 left-3 size-4 -translate-y-1/2 text-muted-foreground" />
          <Input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search name, admission no or student ID" className="pl-9" />
        </div>
        <Select value={status} onValueChange={setStatus}>
          <SelectTrigger className="w-44"><SelectValue /></SelectTrigger>
          <SelectContent>
            {STATUSES.map((s) => <SelectItem key={s} value={s}>{s.replace("_", " ")}</SelectItem>)}
          </SelectContent>
        </Select>
      </div>

      <div className="card-nuru overflow-x-auto">
        <Table>
          <TableHeader>
            <TableRow>
              <TableHead>Admission No</TableHead>
              <TableHead>Student ID</TableHead>
              <TableHead>Name</TableHead>
              <TableHead>Grade</TableHead>
              <TableHead>Guardian</TableHead>
              <TableHead>Status</TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {isLoading ? (
              <TableRow><TableCell colSpan={6} className="py-10 text-center text-muted-foreground">Loading…</TableCell></TableRow>
            ) : filtered.length === 0 ? (
              <TableRow><TableCell colSpan={6} className="py-10 text-center text-muted-foreground">No learners match this filter.</TableCell></TableRow>
            ) : filtered.map((s) => (
              <TableRow key={s.id}>
                <TableCell className="font-mono text-xs font-medium">{s.adm_no}</TableCell>
                <TableCell className="font-mono text-xs">{s.student_id ?? "—"}</TableCell>
                <TableCell className="font-medium">{s.first_name} {s.last_name}</TableCell>
                <TableCell>
                  {(s.grades as { name?: string } | null)?.name ?? "—"}
                  {(s.streams as { name?: string } | null)?.name ? ` ${(s.streams as { name?: string }).name}` : ""}
                </TableCell>
                <TableCell className="text-sm text-muted-foreground">{s.guardian_phone ?? "—"}</TableCell>
                <TableCell><Badge variant={s.status === "active" ? "default" : "secondary"}>{s.status}</Badge></TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </div>
    </AppShell>
  );
}
